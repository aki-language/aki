base::StringU8 CreateUniqueSymbolName(const base::StringRefU8 namespace_name,
                                      const base::StringRefU8 symbol_name) {
  if (!feature_flags::MangleTranslatedSymbols)
    return base::MakeStringCopy(symbol_name);

  if (namespace_name != u8"$$$GLOBAL$$$") {
  }
  base::StringU8 name(base::MakeStringCopy(namespace_name));
  name.erase(std::remove(name.begin(), name.end(), u8'\0'), name.end());
  name += u8"_";
  auto fuckThis = std::to_string(
      base::FNV1a64(reinterpret_cast<const char*>(symbol_name.data())));
  name += (const char8_t*)fuckThis.c_str();
  name += u8"_";
  name += base::MakeStringCopy(symbol_name);
  return name;
}

// for f128 we need to optionally define a symbol custom
base::StringU8 ResolveTypeBit(const base::StringU8& type_core) {
  // fp exit
  if (type_core.length() < 2 && type_core.length() > 4) {
    return u8"auto";
  }
  // todo: we really ought to emit compiler specic core types here.
  base::StringU8 str;
  switch (type_core.c_str()[0]) {
    case 'f':
      if (type_core.c_str()[1] == '3' && type_core.c_str()[2] == '2') {
        str = u8"float";
      } else if (type_core.c_str()[1] == '6' && type_core.c_str()[2] == '4') {
        str = u8"double";
      }
      break;
    case 'i':
      if (type_core.c_str()[1] == '8') {
        str = u8"int8_t";
      } else if (type_core.c_str()[1] == '1' && type_core.c_str()[2] == '6') {
        str = u8"int16_t";
      } else if (type_core.c_str()[1] == '3' && type_core.c_str()[2] == '2') {
        str = u8"int32_t";
      } else if (type_core.c_str()[1] == '6' && type_core.c_str()[2] == '4') {
        str = u8"int64_t";
      }
      break;
    case 'u':
      if (type_core.c_str()[1] == '8') {
        str = u8"uint8_t";
      } else if (type_core.c_str()[1] == '1' && type_core.c_str()[2] == '6') {
        str = u8"uint16_t";
      } else if (type_core.c_str()[1] == '3' && type_core.c_str()[2] == '2') {
        str = u8"uint32_t";
      } else if (type_core.c_str()[1] == '6' && type_core.c_str()[2] == '4') {
        str = u8"uint64_t";
      }
      break;
    case 'c':
      if (type_core.c_str()[1] == '8') {
        str = u8"char";
      } else if (type_core.c_str()[1] == '1' && type_core.c_str()[2] == '6') {
        str = u8"uint16_t";
      } else if (type_core.c_str()[1] == '3' && type_core.c_str()[2] == '2') {
        str = u8"uint32_t";
      }
      break;
    case 'b':
      if (type_core[0] == 'b' && type_core[1] == 'o' && type_core[2] == 'o' &&
          type_core[3] == 'l') {
        str = u8"char";
      }
      break;
  }

  return str.empty() ? u8"auto" : str;
}
